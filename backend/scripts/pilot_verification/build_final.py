NOTE = ("Final pilot event set (20 events), checked on " + CHECKED + " under the rules in docs/data-decisions.md: "
        "FIRMS _SP + AirNow, nearest in-box AirNow site <= 40 km from the fire, best site >= 75% of hours, "
        "< 20% of in-box FRP from other fires, and (non-Low tiers) peak elevation over the pre-event baseline. "
        "Tiers are computed from the max in-box AirNow peak daily mean (EPA 2024 AQI breakpoints). Each bbox is "
        "centred on the event's FRP-weighted FIRMS _SP cluster, widened only to reach the nearest AirNow site within "
        "40 km (see bbox_note). Generated by backend/scripts/pilot_verification/build_final.py; the full check is in "
        "backend/scripts/pilot_verification/reports/final_check.md.")


def nm(s):
    return s.replace("  ", " ")


def entry(ev, r, s1, e):
    eid, name, _, start, end, counties, anchor = ev
    region, nws, pa = CARDS[eid]
    c = s1["cluster"]
    note = (f"Centred on the FRP-weighted centroid of the event's FIRMS _SP cluster ({c['lat']:.3f}, {c['lon']:.3f}): "
            "the cluster's FRP-weighted 98th-percentile extent plus a 25 km buffer, symmetric about the centroid. "
            f"{r['width_km']} x {r['height_km']} km.")
    if r.get("bbox_adjust"):
        computed = ",".join(f"{v:.2f}" for v in r["bbox_computed"])
        note += f" Computed bbox {computed}; {r['bbox_adjust']}."
    note += (f" Other fires: {r.get('other_detections', 0):,} detections, "
             f"{100 * (r.get('other_frp_share') or 0):.1f}% of in-box FRP.")
    prods = products_for(start, end)
    counts = r["firms_counts"]
    n, b = e["nearest"], e["best"]
    i3_site = f"{nm(e['tier_site_name'])} ({e['tier_site']})"
    return {
        "event_id": eid,
        "name": name,
        "region": region,
        "tier": e["tier"],
        "start_date": start,
        "end_date": end,
        "bbox": ",".join(f"{v:.2f}" for v in r["bbox"]),
        "bbox_note": note,
        "nws_grid": nws,
        "airnow_monitors_nearby": [nm(s["name"]) for s in r["sites"] if s["pct_hours"] > 0],
        "purpleair_density": pa,
        "firms_products": prods,
        "firms_products_note": "Archive (_SP) products with detections in the event bbox and window: "
                               + ", ".join(f"{p} {counts.get(p, 0):,}" for p in prods)
                               + ". VIIRS_NOAA21 has no _SP product. Fire features use VIIRS_SNPP only "
                                 "(docs/data-decisions.md #13).",
        "verification_status": "firms_airnow_verified",
        "verification_note": (
            f"Checked {CHECKED} under docs/data-decisions.md: tier site {i3_site}, peak daily PM2.5 "
            f"{e['peak']} µg/m³ on {e['peak_day']}; baseline {e['baseline']} µg/m³ ({e['baseline_source']}); "
            f"nearest in-box AirNow site {nm(n['name'])} ({n['aqs']}) {n['dist_fire_km']} km from the fire; "
            f"best site {nm(b['name'])} ({b['aqs']}) {b['pct_hours']}% of hours. AirNow preliminary data."),
    }


def main():
    S1, S2, I3, I6 = (json.loads((OUT / n).read_text()) for n in ("stage1.json", "stage2.json", "item3.json", "item6.json"))
    events = []
    for ev in EVENTS:
        eid = ev[0]
        e = evaluate(S2[eid], I3.get(eid), I6.get(eid))
        if not e["pass"]:
            sys.exit(f"{eid} fails the final rules; not writing {CONFIG.name}")
        events.append(entry(ev, S2[eid], S1[eid], e))
    cfg = json.loads(CONFIG.read_text())
    cfg = {k: (NOTE if k == "_note" else events if k == "events" else v) for k, v in cfg.items()}
    CONFIG.write_text(json.dumps(cfg, indent=2, ensure_ascii=False) + "\n")
    print(f"wrote {len(events)} events to {CONFIG}")


if __name__ == "__main__":
    if EVENTS_MODULE.__name__ != "events_final":
        sys.exit("run with PILOT_EVENTS=final")
    main()
