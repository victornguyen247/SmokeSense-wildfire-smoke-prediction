// Generates the frontend's copy of the PM-02 API contract from docs/api/:
//
//   src/api/types.ts      TypeScript types for every path and schema (openapi-typescript)
//   src/mocks/fixtures.ts every docs/api/fixtures/*.json, each checked against its
//                         response type with `satisfies`, so `npm run build` fails if a
//                         fixture and the spec disagree
//
// Both files are committed, because the frontend Docker build only sees frontend/ and
// cannot read docs/api/. Never edit them by hand; rerun this script.
//
//   npm run gen:api     regenerate both files
//   npm run api:check   fail if either file is out of date (run in CI)

import { readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const FRONTEND_DIR = join(dirname(fileURLToPath(import.meta.url)), "..");
const API_DIR = join(FRONTEND_DIR, "..", "docs", "api");
const SPEC_PATH = join(API_DIR, "openapi.yaml");
const FIXTURE_DIR = join(API_DIR, "fixtures");
const MANIFEST_PATH = join(API_DIR, "fixture_manifest.json");
const TYPES_OUT = join(FRONTEND_DIR, "src", "api", "types.ts");
const FIXTURES_OUT = join(FRONTEND_DIR, "src", "mocks", "fixtures.ts");

// Forward slashes on every OS, so a Windows checkout generates the same files as CI.
const posixRelative = (path) => relative(FRONTEND_DIR, path).split(sep).join("/");

const HEADER = (source) =>
  `// GENERATED by scripts/sync-api.mjs from ${source}. Do not edit by hand;\n` +
  `// run \`npm run gen:api\` after the API contract changes.\n\n`;

const toIdentifier = (file) =>
  file.replace(/\.json$/, "").replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());

async function buildTypes() {
  const spec = await readFile(SPEC_PATH, "utf8");
  const ast = await openapiTS(spec);
  return HEADER(posixRelative(SPEC_PATH)) + astToString(ast);
}

async function buildFixtures() {
  // fixture file -> [{path, status}, ...], shared with docs/api/validate.py and the
  // backend contract tests.
  const { fixtures } = JSON.parse(await readFile(MANIFEST_PATH, "utf8"));
  const onDisk = (await readdir(FIXTURE_DIR)).filter((f) => f.endsWith(".json")).sort();
  const unmapped = onDisk.filter((f) => !(f in fixtures));
  const missing = Object.keys(fixtures).filter((f) => !onDisk.includes(f));
  if (unmapped.length || missing.length) {
    throw new Error(
      `Fixture list out of sync with docs/api/fixtures. ` +
        `Not mapped: [${unmapped.join(", ")}]. Missing: [${missing.join(", ")}]. ` +
        `Update docs/api/fixture_manifest.json.`,
    );
  }

  const parts = [
    HEADER(posixRelative(FIXTURE_DIR) + "/*.json"),
    'import type { paths } from "../api/types";\n\n',
    "/** Body of a GET response, as declared in the spec. */\n",
    "type Body<P extends keyof paths, S extends number> =\n",
    '  paths[P]["get"]["responses"] extends Record<S, { content: { "application/json": infer B } }>\n',
    "    ? B\n",
    "    : never;\n",
  ];
  for (const file of onDisk) {
    const uses = fixtures[file];
    const body = JSON.parse(await readFile(join(FIXTURE_DIR, file), "utf8"));
    const doc = uses.map(({ path, status }) => `GET ${path} ${status}`).join(", ");
    const checks = uses.map(({ path, status }) => ` satisfies Body<"${path}", ${status}>`).join("");
    parts.push(
      `\n/** docs/api/fixtures/${file}: ${doc} */\n`,
      `export const ${toIdentifier(file)} = ${JSON.stringify(body, null, 2)}${checks};\n`,
    );
  }
  return parts.join("");
}

async function main() {
  const check = process.argv.includes("--check");
  const outputs = [
    [TYPES_OUT, await buildTypes()],
    [FIXTURES_OUT, await buildFixtures()],
  ];

  let stale = false;
  for (const [path, content] of outputs) {
    const name = posixRelative(path);
    if (check) {
      // Ignore CRLF vs LF, so a Windows checkout doesn't fail the check.
      const current = (await readFile(path, "utf8").catch(() => "")).replace(/\r\n/g, "\n");
      if (current !== content) {
        console.error(`out of date: ${name}`);
        stale = true;
      } else {
        console.log(`up to date: ${name}`);
      }
    } else {
      await writeFile(path, content);
      console.log(`wrote ${name}`);
    }
  }

  if (stale) {
    console.error("\nThe API contract in docs/api/ changed. Run `npm run gen:api` in frontend/ and commit.");
    process.exit(1);
  }
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
